#!/usr/bin/env python3
"""Config writes without the multi-second freeze (t6mp.nro and t6zm.nro).

Every time an archived dvar changes (opening the lobby, Setup Bots, after a map loads,
on quit) the game rewrites players/config_mp.cfg / config_zm.cfg with
Com_WriteConfigToFile(): one FS_Printf per line, and the port's fwrite turns each one into
a write() on the SD card of ~10-13 ms. ~250 lines = the ~3 s freezes seen in the
[nx-stall] reports (main thread in Com_WriteConfigToFile -> Dvar_WriteVariables ->
FS_Printf -> FS_Write).

cfg_buf/cfg_buf.bin gathers the lines of that one file in a 1 KB buffer and writes them in
blocks (~7 writes instead of ~250). Three instructions change:
  - Com_WriteConfigToFile: `mov w20, w0` after opening the file -> `bl cfg_begin`
  - FS_Printf: `bl FS_Write` -> `bl cfg_write` (other files go straight on to FS_Write)
  - Com_WriteConfigToFile: tail call `b FS_FCloseFile` -> `b cfg_end` (flushes, closes)
The blob goes over the last 0x400 bytes of .eh_frame (unused: the guest has no unwinder
and nothing reads that section), its state (0x40c bytes) right after .bss.

Usage: python3 patch_config_write.py path/to/t6mp.nro|t6zm.nro [output.nro]
Without [output.nro], overwrites in place and keeps a .bak of the original.
"""
import os
import struct
import sys

from nro_guest import Guest, adrp_target, b_target, bl_target, enc_b, enc_bl, find_guest, write_nro

BLOB = os.path.join(os.path.dirname(os.path.abspath(__file__)), "cfg_buf", "cfg_buf.bin")
SLOT = 0x400                  # bytes at the end of .eh_frame reserved for the blob
BEGIN, WRITE, END = 0x10, 0x14, 0x18
STATE_SIZE = 12 + 0x400       # struct cfg_state in cfg_buf.c
MOV_W20_W0 = 0x2A0003F4
HEADER = "// generated by Call of Duty, do not modify\n"

def add_refs(g, words, s):
    """Indexes of the `add wD, wN, #lo` (any registers) that form the address of string s."""
    targets = set(g.rodata_strings(s))
    hits = []
    for k, (pc, off) in enumerate(words[:-1]):
        page = adrp_target(pc, g.word(off))
        if page is None:
            continue
        rd = g.word(off) & 31
        for j in range(k + 1, min(k + 12, len(words))):
            a = g.word(words[j][1])
            if (a & 0x7FC00000) == 0x11000000 and ((a >> 5) & 31) == rd \
                    and page + ((a >> 10) & 0xFFF) in targets:
                hits.append(j)
                break
    return hits


def find_sites(g, words):
    """Patch sites, as a dict of NRO offsets ("*_off"), VAs ("*_pc") and call targets.

    Works on the original and on an already patched NRO (then the targets are ours)."""
    w = lambda i: g.word(words[i][1])
    pc = lambda i: words[i][0]
    # Com_WriteConfigToFile: add w1, <header>; mov w20, w0 (or our bl); bl FS_Printf; ...;
    # ldp x29, x30, [sp], #0x20; b FS_FCloseFile. Other users of the header string differ.
    refs = [j for j in add_refs(g, words, HEADER)
            if (w(j) & 0x1F) == 1 and (w(j + 1) == MOV_W20_W0 or bl_target(pc(j + 1), w(j + 1)) is not None)
            and bl_target(pc(j + 2), w(j + 2)) is not None and w(j + 9) == 0xA8C27BFD
            and b_target(pc(j + 10), w(j + 10)) is not None]
    if len(refs) != 1:
        raise SystemExit(f"Com_WriteConfigToFile found {len(refs)} times; unsupported version")
    j = refs[0]
    printf = bl_target(pc(j + 2), w(j + 2))
    close = b_target(pc(j + 10), w(j + 10))

    # FS_Printf: three calls (vsnprintf, strlen, FS_Write); the last one is FS_Write
    first = (printf - words[0][0]) // 4
    calls = [k for k in range(first, first + 0x60) if bl_target(pc(k), w(k)) is not None]
    if len(calls) != 3:
        raise SystemExit("FS_Printf differs from expected; unsupported version")
    k = calls[2]
    return {"begin_off": words[j + 1][1], "begin_pc": pc(j + 1),
            "close_off": words[j + 10][1], "close_pc": pc(j + 10), "close": close,
            "write_off": words[k][1], "write_pc": pc(k), "write": bl_target(pc(k), w(k))}


def string_ref_fn(g, words, s):
    """Start of the function that references string s within its first 0x40 bytes."""
    found = set()
    for j in add_refs(g, words, s):
        for k in range(j, max(j - 16, 0), -1):
            if (g.word(words[k][1]) & 0xFFC07FFF) == 0xA9807BFD:   # stp x29, x30, [sp, #-N]!
                found.add(words[k][0])
                break
    return found.pop() if len(found) == 1 else None


def main():
    if len(sys.argv) not in (2, 3):
        raise SystemExit(__doc__)
    src = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) == 3 else src
    nro = bytearray(open(src, "rb").read())
    name, start = find_guest(nro)
    g = Guest(nro, start)
    words = g.text_words()

    s = find_sites(g, words)
    eh_addr, _, eh_size = g.secs[".eh_frame"]
    cave = (eh_addr + eh_size - SLOT) & ~15
    if s["write"] == cave + WRITE:
        print("already patched; nothing to do")
        return
    fs_write = string_ref_fn(g, words, "FS_Write")
    if s["write"] != fs_write or g.word(s["begin_off"]) != MOV_W20_W0:
        raise SystemExit("config write code differs from expected; unsupported version")

    blob = bytearray(open(BLOB, "rb").read())
    if len(blob) > SLOT - 16:
        raise SystemExit("cfg_buf.bin does not fit in its slot")
    state = g.alloc_bss(STATE_SIZE)
    struct.pack_into("<4I", blob, 0, fs_write, s["close"], state, cave)
    raw = g.va_to_off(cave)
    nro[raw:raw + len(blob)] = blob
    g.put(s["begin_off"], enc_bl(s["begin_pc"], cave + BEGIN))
    g.put(s["write_off"], enc_bl(s["write_pc"], cave + WRITE))
    g.put(s["close_off"], enc_b(s["close_pc"], cave + END))
    write_nro(nro, src, dst, [
        f"{name}: buffered config writes (code at 0x{cave:x} in .eh_frame, state 0x{state:x});"
        f" FS_Write 0x{fs_write:x}, FS_FCloseFile 0x{s['close']:x},"
        f" sites 0x{s['begin_pc']:x} 0x{s['write_pc']:x} 0x{s['close_pc']:x}"])


if __name__ == "__main__":
    main()
